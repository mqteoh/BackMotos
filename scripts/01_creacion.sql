CREATE FUNCTION fn_cuenta_rol() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.rol = 'VENDEDOR' AND NOT EXISTS (SELECT 1 FROM vendedor WHERE id_empleado = NEW.id_empleado) THEN
        RAISE EXCEPTION 'El empleado no está registrado como vendedor' USING ERRCODE = '45000';
    END IF;
    IF NEW.rol = 'TECNICO' AND NOT EXISTS (SELECT 1 FROM tecnico WHERE id_empleado = NEW.id_empleado) THEN
        RAISE EXCEPTION 'El empleado no está registrado como técnico' USING ERRCODE = '45000';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_cuenta_rol BEFORE INSERT OR UPDATE ON cuenta FOR EACH ROW EXECUTE FUNCTION fn_cuenta_rol();

CREATE FUNCTION fn_reserva_bi() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.estado = 'ACTIVA' AND (SELECT estado FROM moto WHERE placa = NEW.placa) <> 'DISPONIBLE' THEN
        RAISE EXCEPTION 'La moto no está disponible para reservar' USING ERRCODE = '45000';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_reserva_bi BEFORE INSERT ON reserva FOR EACH ROW EXECUTE FUNCTION fn_reserva_bi();

CREATE FUNCTION fn_reserva_bu() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.estado = 'ACTIVA' AND OLD.estado <> 'ACTIVA' THEN
        RAISE EXCEPTION 'Una reserva cerrada no se puede volver a activar' USING ERRCODE = '45000';
    END IF;
    IF NEW.estado = 'CONCRETADA' AND OLD.estado <> 'CONCRETADA'
        AND NOT EXISTS (SELECT 1 FROM venta_moto WHERE placa = NEW.placa AND id_cliente = NEW.id_cliente) THEN
        RAISE EXCEPTION 'Una reserva solo se concreta registrando la venta' USING ERRCODE = '45000';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_reserva_bu BEFORE UPDATE ON reserva FOR EACH ROW EXECUTE FUNCTION fn_reserva_bu();

CREATE FUNCTION fn_reserva_estado_moto() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' AND NEW.estado = 'ACTIVA' THEN
        UPDATE moto SET estado = 'RESERVADA' WHERE placa = NEW.placa;
    ELSIF TG_OP = 'UPDATE' AND OLD.estado = 'ACTIVA' AND NEW.estado IN ('CANCELADA','VENCIDA') THEN
        UPDATE moto SET estado = 'DISPONIBLE' WHERE placa = NEW.placa AND estado = 'RESERVADA';
    END IF;
    RETURN NULL;
END $$;
CREATE TRIGGER trg_reserva_estado_moto AFTER INSERT OR UPDATE ON reserva FOR EACH ROW EXECUTE FUNCTION fn_reserva_estado_moto();

CREATE FUNCTION fn_venta_moto_bi() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM reserva WHERE placa = NEW.placa AND estado = 'ACTIVA' AND id_cliente <> NEW.id_cliente) THEN
        RAISE EXCEPTION 'La moto está reservada por otro cliente' USING ERRCODE = '45000';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_venta_moto_bi BEFORE INSERT ON venta_moto FOR EACH ROW EXECUTE FUNCTION fn_venta_moto_bi();

CREATE FUNCTION fn_venta_moto_ai() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE moto SET estado = 'VENDIDA' WHERE placa = NEW.placa;
    UPDATE reserva SET estado = 'CONCRETADA' WHERE placa = NEW.placa AND estado = 'ACTIVA' AND id_cliente = NEW.id_cliente;
    RETURN NULL;
END $$;
CREATE TRIGGER trg_venta_moto_ai AFTER INSERT ON venta_moto FOR EACH ROW EXECUTE FUNCTION fn_venta_moto_ai();

CREATE FUNCTION fn_venta_moto_ad() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE moto SET estado = 'DISPONIBLE' WHERE placa = OLD.placa;
    RETURN NULL;
END $$;
CREATE TRIGGER trg_venta_moto_ad AFTER DELETE ON venta_moto FOR EACH ROW EXECUTE FUNCTION fn_venta_moto_ad();

CREATE FUNCTION fn_detalle_accesorio_total() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    venta INTEGER;
BEGIN
    venta := CASE WHEN TG_OP = 'DELETE' THEN OLD.id_venta ELSE NEW.id_venta END;
    UPDATE venta_accesorio
    SET valor_total = (SELECT COALESCE(SUM(cantidad * precio_unitario), 0) FROM detalle_accesorio WHERE id_venta = venta)
    WHERE id_venta = venta;
    RETURN NULL;
END $$;
CREATE TRIGGER trg_detalle_accesorio_total AFTER INSERT OR UPDATE OR DELETE ON detalle_accesorio
    FOR EACH ROW EXECUTE FUNCTION fn_detalle_accesorio_total();

CREATE FUNCTION fn_reparacion_bi() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    vendida DATE;
BEGIN
    SELECT CAST(fecha_venta AS DATE) INTO vendida FROM venta_moto WHERE placa = NEW.placa;
    IF vendida IS NULL THEN
        RAISE EXCEPTION 'El taller solo atiende motos vendidas por el concesionario' USING ERRCODE = '45000';
    END IF;
    IF NEW.fecha < vendida THEN
        RAISE EXCEPTION 'La reparación no puede ser anterior a la venta de la moto' USING ERRCODE = '45000';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_reparacion_bi BEFORE INSERT OR UPDATE ON reparacion FOR EACH ROW EXECUTE FUNCTION fn_reparacion_bi();

CREATE FUNCTION fn_tecnicos_reparacion_bi() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM tecnicos_reparacion tr JOIN empleado e ON e.id_empleado = tr.id_empleado
               WHERE tr.id_reparacion = NEW.id_reparacion
                 AND e.id_sucursal <> (SELECT id_sucursal FROM empleado WHERE id_empleado = NEW.id_empleado)) THEN
        RAISE EXCEPTION 'Los técnicos de una reparación deben ser de la misma sede' USING ERRCODE = '45000';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_tecnicos_reparacion_bi BEFORE INSERT ON tecnicos_reparacion FOR EACH ROW EXECUTE FUNCTION fn_tecnicos_reparacion_bi();
